// FireFlammability 返回方块状态的火焰数值（原版 FireBlock.getBurnOdds 与
// getFlammability）：encouragement 是蔓延鼓励值（> 0 即“可燃”，0 表示不可燃），
// flammability 是接触火焰时的燃烧速率。未收录的方块与不可识别状态返回 0，0。
//
// 偏差：原版对水方块状态（waterlogged=true）返回 0，0；gmcs 不建模该属性
// （也不生成这类状态，见 block_states_generated.go 收录的方块），因此此处不特殊处理。
func FireFlammability(state uint16) (encouragement, flammability int) {
	name, ok := BlockNameByState(state)
	if !ok {
		return 0, 0
	}
	values, ok := fireFlammables[name]
	if !ok {
		return 0, 0
	}
	return values.encouragement, values.flammability
}
