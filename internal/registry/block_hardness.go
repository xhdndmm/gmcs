// BlockHardness 返回方块的硬度（原版 destroyTime）与是否要求正确工具。
// 未收录的方块与不可识别状态返回 0, false；-1 表示不可破坏。
func BlockHardness(state uint16) (hardness float32, requiresCorrectTool bool) {
	name, ok := BlockNameByState(state)
	if !ok {
		return 0, false
	}
	values, ok := blockHardnessValues[name]
	if !ok {
		return 0, false
	}
	return values.hardness, values.requires
}
