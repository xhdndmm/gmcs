// writeBlockFlags 生成方块行为数据表。
func writeBlockFlags(outDir, version string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/genregistries from Minecraft %s\n", version)
	fmt.Fprintf(&b, "// （由官方 mappings + 反编译的 Blocks.java 提取，见 tools/genregistries/flags.go）；DO NOT EDIT.\n")
	fmt.Fprintf(&b, "\npackage registry\n\n")
	fmt.Fprintf(&b, "// PushReaction 是方块的活塞推动行为（与原版 PushReaction 枚举对应）。\n")
	fmt.Fprintf(&b, "type PushReaction uint8\n\n")
	fmt.Fprintf(&b, "const (\n")
	fmt.Fprintf(&b, "\tPushReactionNormal PushReaction = iota\n")
	fmt.Fprintf(&b, "\tPushReactionDestroy\n")
	fmt.Fprintf(&b, "\tPushReactionBlock\n")
	fmt.Fprintf(&b, "\tPushReactionPushOnly\n")
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// pushReactionOverrides 保存非 NORMAL 的推反应。\n")
	fmt.Fprintf(&b, "var pushReactionOverrides = map[string]PushReaction{\n")
	exprGo := map[string]string{"DESTROY": "PushReactionDestroy", "BLOCK": "PushReactionBlock", "PUSH_ONLY": "PushReactionPushOnly", "IGNORE": "pushReactionIgnore"}
	for i, name := range pushReactionNames {
		fmt.Fprintf(&b, "\t%q: %s,\n", name, exprGo[pushReactionExpr[i]])
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "// PushReactionOf 返回方块名的推反应（默认 Normal）。\n")
	fmt.Fprintf(&b, "func PushReactionOf(name string) PushReaction {\n")
	fmt.Fprintf(&b, "\tif r, ok := pushReactionOverrides[name]; ok {\n")
	fmt.Fprintf(&b, "\t\treturn r\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\treturn PushReactionNormal\n")
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "var nonConductiveBlocks = map[string]bool{\n")
	for _, name := range nonConductiveNames {
		fmt.Fprintf(&b, "\t%q: true,\n", name)
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "var alwaysConductiveBlocks = map[string]bool{\n")
	for _, name := range alwaysConductiveNames {
		fmt.Fprintf(&b, "\t%q: true,\n", name)
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "// IsRedstoneConductor 报告方块是否导强充能：显式覆盖优先，\n")
	fmt.Fprintf(&b, "// 否则使用“碰撞形状为整方块”的默认判定。\n")
	fmt.Fprintf(&b, "func IsRedstoneConductor(name string, fullCube bool) bool {\n")
	fmt.Fprintf(&b, "\tif alwaysConductiveBlocks[name] {\n")
	fmt.Fprintf(&b, "\t\treturn true\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\tif nonConductiveBlocks[name] {\n")
	fmt.Fprintf(&b, "\t\treturn false\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\treturn fullCube\n")
	fmt.Fprintf(&b, "}\n")

	source := []byte(b.String())
	formatted, err := format.Source(source)
	if err != nil {
		return fmt.Errorf("格式化生成代码：%w（原始内容长度 %d）", err, len(source))
	}
	path := filepath.Join(outDir, "block_flags_generated.go")
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("已生成方块行为表（推反应 %d 项、非导体 %d 项、导体 %d 项）\n", len(pushReactionNames), len(nonConductiveNames), len(alwaysConductiveNames))
	return nil
}
