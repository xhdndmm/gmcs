// writeBlockPropertyStates 生成方块属性状态表。
func writeBlockPropertyStates(outDir, version string, blocks map[string]blockShapeData) error {
	var b strings.Builder
	b.WriteString(licenseHeader)
	fmt.Fprintf(&b, "// Code generated by tools/genregistries from Minecraft %s reports/blocks.json; DO NOT EDIT.\n", version)
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// 需要按属性查询的方块状态表（红石、传送门、双格植物等）。\n")
	fmt.Fprintf(&b, "// 运行时使用 registry.BlockStateWithProps 按属性匹配状态 ID；\n")
	fmt.Fprintf(&b, "// 需要新方块时修改 tools/genregistries/blockstates.go 的 propStateBlocks。\n")
	fmt.Fprintf(&b, "\npackage registry\n\n")

	names := append([]string(nil), propStateBlocks...)
	sort.Strings(names)
	missing := make([]string, 0)
	total := 0
	fmt.Fprintf(&b, "// BlockPropertyStates 是参与属性匹配的方块的全部状态。\n")
	fmt.Fprintf(&b, "var BlockPropertyStates = map[string][]PropertyState{\n")
	for _, name := range names {
		data, ok := blocks[name]
		if !ok {
			missing = append(missing, name)
			continue
		}
		states := append([]stateShapeData(nil), data.states...)
		sort.Slice(states, func(i, j int) bool { return states[i].id < states[j].id })
		fmt.Fprintf(&b, "\t%q: {\n", name)
		for _, state := range states {
			keys := make([]string, 0, len(state.props))
			for key := range state.props {
				keys = append(keys, key)
			}
			sort.Strings(keys)
			parts := make([]string, 0, len(keys))
			for _, key := range keys {
				parts = append(parts, fmt.Sprintf("%q: %q", key, state.props[key]))
			}
			fmt.Fprintf(&b, "\t\t{ID: %d, Props: map[string]string{%s}},\n", state.id, strings.Join(parts, ", "))
		}
		fmt.Fprintf(&b, "\t},\n")
		total += len(states)
	}
	fmt.Fprintf(&b, "}\n")
	if len(missing) > 0 {
		return fmt.Errorf("blocks.json 缺少方块：%s", strings.Join(missing, "、"))
	}

	source := []byte(b.String())
	formatted, err := format.Source(source)
	if err != nil {
		return fmt.Errorf("格式化生成代码：%w（原始内容长度 %d）", err, len(source))
	}
	path := filepath.Join(outDir, "block_states_generated.go")
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("已生成方块属性状态表（%d 个方块、%d 个状态）\n", len(names), total)
	return nil
}

// writeBlockStateNames 生成“状态 ID → 方块名”区间表（原版方块状态 ID 连续，
// 因此每个方块只需保存起止 ID 即可二分查找）。
func writeBlockStateNames(outDir, version string, blocks map[string]blockShapeData) error {
	type stateRange struct {
		start, end uint16
		name       string
	}
	ranges := make([]stateRange, 0, len(blocks))
	for name, data := range blocks {
		if len(data.states) == 0 {
			continue
		}
		minID, maxID := uint16(0xFFFF), uint16(0)
		for _, state := range data.states {
			if state.id < minID {
				minID = state.id
			}
			if state.id > maxID {
				maxID = state.id
			}
		}
		ranges = append(ranges, stateRange{start: minID, end: maxID, name: name})
	}
	sort.Slice(ranges, func(i, j int) bool { return ranges[i].start < ranges[j].start })

	var b strings.Builder
	b.WriteString(licenseHeader)
	fmt.Fprintf(&b, "// Code generated by tools/genregistries from Minecraft %s reports/blocks.json; DO NOT EDIT.\n", version)
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// 状态 ID → 方块名区间表（原版方块状态 ID 连续，二分查找）。\n")
	fmt.Fprintf(&b, "\npackage registry\n\n")
	fmt.Fprintf(&b, "// BlockStateRange 是一个方块的全部状态 ID 区间。\n")
	fmt.Fprintf(&b, "type BlockStateRange struct {\n\tStart, End uint16\n\tName       string\n}\n\n")
	fmt.Fprintf(&b, "// blockStateNameRanges 按 Start 升序保存每个方块的状态区间。\n")
	fmt.Fprintf(&b, "var blockStateNameRanges = []BlockStateRange{\n")
	for _, r := range ranges {
		fmt.Fprintf(&b, "\t{%d, %d, %q},\n", r.start, r.end, r.name)
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "// BlockNameByState 返回状态所属方块的命名空间名。\n")
	fmt.Fprintf(&b, "func BlockNameByState(state uint16) (string, bool) {\n")
	fmt.Fprintf(&b, "\tlo, hi := 0, len(blockStateNameRanges)-1\n")
	fmt.Fprintf(&b, "\tfor lo <= hi {\n")
	fmt.Fprintf(&b, "\t\tmid := (lo + hi) / 2\n")
	fmt.Fprintf(&b, "\t\tr := blockStateNameRanges[mid]\n")
	fmt.Fprintf(&b, "\t\tswitch {\n")
	fmt.Fprintf(&b, "\t\tcase state < r.Start:\n")
	fmt.Fprintf(&b, "\t\t\thi = mid - 1\n")
	fmt.Fprintf(&b, "\t\tcase state > r.End:\n")
	fmt.Fprintf(&b, "\t\t\tlo = mid + 1\n")
	fmt.Fprintf(&b, "\t\tdefault:\n")
	fmt.Fprintf(&b, "\t\t\treturn r.Name, true\n")
	fmt.Fprintf(&b, "\t\t}\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\treturn \"\", false\n")
	fmt.Fprintf(&b, "}\n")

	source := []byte(b.String())
	formatted, err := format.Source(source)
	if err != nil {
		return fmt.Errorf("格式化生成代码：%w（原始内容长度 %d）", err, len(source))
	}
	path := filepath.Join(outDir, "block_state_names_generated.go")
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("已生成状态名区间表（%d 个方块）\n", len(ranges))
	return nil
}
